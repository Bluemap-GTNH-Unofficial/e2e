"""Oracle cameras on the machines of a plaza scene (``endgame``), generated from the orchestrator's ``scene.json``.

``uv run python -m e2e.oracle.machine_cameras [--scene endgame] [--check]`` rewrites the generated block of
``scenes/<scene>.yaml`` (between the ``BEGIN``/``END`` marker comments under ``oracle.cameras``) with one camera per
entry of ``machines`` in ``out/scenes-<version>/<scene>/scene.json``; ``--check`` only reports whether the block is up to
date (exit 1 if not). The framing is the site demo's (``site/scripts/build-demo.ts``: ``MACHINE_VIEW``, ``FLAT_VIEW``,
``FLAT_MACHINES``, ``fitDistance``): seen from the north-west at the webapp rotation/angle given there, pulled back
until every corner of the machine's box is inside ``margin`` of the view, but with the oracle's vertical field of view
and image size and the box centre as the target (the client has no terrain-height rule for the camera height).
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from dataclasses import dataclass

import numpy as np
import yaml

from e2e import paths
from e2e.oracle import camera as cameras

BEGIN = "# BEGIN generated by `uv run python -m e2e.oracle.machine_cameras`"
END = "# END generated"
MIN_DISTANCE = 5.0  # the webapp's minimum zoom distance, as in the demo


@dataclass(frozen=True)
class Framing:
    rotation: float  # webapp rotation, radians (0 looks north, PI/2 east)
    angle: float  # webapp angle, radians (0 looks straight down, PI/2 level)
    margin: float  # share of the view the box may fill


MACHINE_VIEW = Framing(rotation=2.5, angle=1.0, margin=0.86)
FLAT_VIEW = Framing(rotation=2.5, angle=0.78, margin=0.86)  # flat machines, from higher up
FLAT_MACHINES = re.compile(r"^(fusion-mk|compact-fusion-mk|lhc$)")


def look_direction(rotation: float, angle: float) -> np.ndarray:
    """The webapp's view direction (``build-demo.ts`` ``lookDirection``, ``camera.from_view``)."""
    return np.array([math.sin(rotation) * math.sin(angle), -math.cos(angle), -math.cos(rotation) * math.sin(angle)])


def centre(box: list[int]) -> np.ndarray:
    """Centre of an inclusive block box ``[x0, y0, z0, x1, y1, z1]``."""
    x0, y0, z0, x1, y1, z1 = box
    return np.array([(x0 + x1 + 1) / 2, (y0 + y1 + 1) / 2, (z0 + z1 + 1) / 2])


def fit_distance(box: list[int], target: np.ndarray, framing: Framing, fov: float, size: tuple[int, int]) -> float:
    """The smallest distance back from ``target`` at which every corner of ``box`` is inside the view (vertical field
    of view ``fov`` in degrees, image ``size``) scaled by the margin (``build-demo.ts`` ``fitDistance``)."""
    forward = look_direction(framing.rotation, framing.angle)
    side = np.cross(forward, [0.0, 1.0, 0.0])
    right = np.array([side[0], 0.0, side[2]]) / math.hypot(side[0], side[2])
    up = np.cross(right, forward)
    tan_v = math.tan(math.radians(fov) / 2) * framing.margin
    tan_h = tan_v * size[0] / size[1]
    x0, y0, z0, x1, y1, z1 = box
    distance = MIN_DISTANCE
    for x in (x0, x1 + 1):
        for y in (y0, y1 + 1):
            for z in (z0, z1 + 1):
                p = np.array([x, y, z], dtype=float) - target
                depth = float(p @ forward)
                distance = max(distance, abs(float(p @ right)) / tan_h - depth, abs(float(p @ up)) / tan_v - depth)
    return distance


def machine_camera(machine: dict, fov: float, size: tuple[int, int],
                   plaza: list[int] | None = None) -> tuple[np.ndarray, np.ndarray]:
    """``(eye, look_at)`` of one machine: its box centre, seen from the fitted distance. With ``plaza`` (the scene's
    box), an eye that would lie outside it horizontally is moved towards the target onto its edge: the client then
    stands over the scene's own chunks (the Forge of the Gods' fitted eye at x -16.6 never got the chunks it waits for)."""
    framing = FLAT_VIEW if FLAT_MACHINES.match(machine["key"]) else MACHINE_VIEW
    target = centre(machine["box"])
    direction = look_direction(framing.rotation, framing.angle)
    distance = fit_distance(machine["box"], target, framing, fov, size)
    if plaza is not None:
        for axis, low, high in ((0, plaza[0], plaza[3] + 1), (2, plaza[2], plaza[5] + 1)):
            back = -direction[axis]  # eye = target + distance * back along this axis
            if back < 0:
                distance = min(distance, (target[axis] - low) / -back)
            elif back > 0:
                distance = min(distance, (high - target[axis]) / back)
    return target - distance * direction, target


def _numbers(values: np.ndarray) -> str:
    return "[" + ", ".join(f"{float(v):g}" for v in np.round(values, 2)) + "]"


def generated_block(scene: dict, fov: float, size: tuple[int, int], indent: str) -> list[str]:
    """The lines between (and including) the marker comments."""
    lines = [f"{indent}{BEGIN} from scene.json; do not edit", f"{indent}# ({len(scene['machines'])} machines)"]
    for machine in scene["machines"]:
        eye, target = machine_camera(machine, fov, size, (scene.get("plaza") or {}).get("box"))
        lines.append(f"{indent}{machine['key']}: {{eye: {_numbers(eye)}, look_at: {_numbers(target)}}}"
                     f"  # {machine['label']}, tier {machine['tier']}")
    lines.append(f"{indent}{END}")
    return lines


def update(text: str, scene: dict) -> str:
    """``text`` (a scene YAML) with its generated camera block replaced, sized by its ``oracle`` settings."""
    lines = text.splitlines()
    begin = next((i for i, line in enumerate(lines) if line.strip().startswith(BEGIN)), None)
    end = next((i for i, line in enumerate(lines) if line.strip() == END), None)
    if begin is None or end is None or end < begin:
        raise ValueError(f"no `{BEGIN}` ... `{END}` block")
    raw = yaml.safe_load(text)
    oracle = raw.get("oracle") or {}
    size = tuple(oracle.get("size", raw.get("viewport", (1280, 720))))
    fov = float(oracle.get("fov", cameras.DEFAULT_FOV))
    indent = lines[begin][: len(lines[begin]) - len(lines[begin].lstrip())]
    return "\n".join([*lines[:begin], *generated_block(scene, fov, size, indent), *lines[end + 1 :]]) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m e2e.oracle.machine_cameras", description=__doc__.split("\n\n")[0])
    parser.add_argument("--scene", default="endgame", help="scene with `machines` in its scene.json (default %(default)s)")
    parser.add_argument("--check", action="store_true", help="exit 1 if the YAML is not up to date, write nothing")
    args = parser.parse_args(argv)
    source = paths.scenes_dir() / args.scene / "scene.json"
    if not source.is_file():
        raise SystemExit(f"{source} does not exist; build the scene with `orch scene {args.scene}`")
    target = paths.SCENES_DIR / f"{args.scene}.yaml"
    text = target.read_text(encoding="utf-8")
    updated = update(text, json.loads(source.read_text(encoding="utf-8")))
    if args.check:
        print(f"{target}: {'up to date' if updated == text else f'out of date with {source}'}")
        return 0 if updated == text else 1
    if updated != text:
        target.write_text(updated, encoding="utf-8", newline="\n")
    print(f"{target}: {'updated' if updated != text else 'up to date'} from {source}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
